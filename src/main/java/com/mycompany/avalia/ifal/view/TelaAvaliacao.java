    private void configurarAlternativas() {
        javax.swing.ButtonGroup grupoAlternativas =
                new javax.swing.ButtonGroup();

        grupoAlternativas.add(RadioAlternativaA);
        grupoAlternativas.add(RadioAlternativaB);
        grupoAlternativas.add(RadioAlternativaC);
        grupoAlternativas.add(RadioAlternativaD);
        grupoAlternativas.add(RadioAlternativaE);

        RadioAlternativaA.addActionListener(e -> mostrarAlternativa("A"));
        RadioAlternativaB.addActionListener(e -> mostrarAlternativa("B"));
        RadioAlternativaC.addActionListener(e -> mostrarAlternativa("C"));
        RadioAlternativaD.addActionListener(e -> mostrarAlternativa("D"));
        RadioAlternativaE.addActionListener(e -> mostrarAlternativa("E"));
    }

    private void mostrarAlternativa(String alternativa) {
        TextoDicaAlternativa.setText(
                "Alternativa marcada: " + alternativa
        );
    }

    private void configurarTemporizador() {
        BotaoProximaQuestao.setEnabled(false);

        BarraProgresso.setMinimum(0);
        BarraProgresso.setMaximum(45);
        BarraProgresso.setValue(0);

        TextoDicaAguarde.setText(
                "Aguarde " + segundos + "s para avançar."
        );

        timer = new javax.swing.Timer(1000, e -> {
            segundos--;

            BarraProgresso.setValue(45 - segundos);

            if (segundos <= 0) {
                segundos = 0;
                timer.stop();

                TextoDicaAguarde.setText("Você já pode avançar.");
                BarraProgresso.setValue(45);
                BotaoProximaQuestao.setEnabled(true);
            } else {
                TextoDicaAguarde.setText(
                        "Aguarde " + segundos + "s para avançar."
                );
            }
        });

        timer.start();
    }

    @Override
    public void dispose() {
        if (timer != null) {
            timer.stop();
        }

        super.dispose();
    }

