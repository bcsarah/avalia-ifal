    private void EntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EntrarActionPerformed
        String login = InputLogin.getText().trim();
        String senha = new String(InputSenha.getPassword());

        if (login.isEmpty() || senha.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Preencha o login e a senha antes de continuar.",
                "Campos obrigatórios",
                javax.swing.JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        Usuario usuarioAutenticado = null;

        for (Usuario usuario : DadosIniciais.criarUsuarios()) {
            if (usuario.autenticar(login, senha)) {
                usuarioAutenticado = usuario;
                break;
            }
        }

        if (usuarioAutenticado == null) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Login ou senha incorretos.",
                "Falha na autenticação",
                javax.swing.JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        switch (usuarioAutenticado.getPerfil()) {
            case "ADMIN" ->
                new TelaAdmin().setVisible(true);

            case "PROFESSOR" ->
                new TelaProfessor().setVisible(true);

            case "ALUNO" ->
                new TelaAvaliacoesDisponiveis().setVisible(true);

            default -> {
                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Perfil de usuário não reconhecido.",
                    "Erro",
                    javax.swing.JOptionPane.ERROR_MESSAGE
                );
                return;
            }
        }

        this.dispose();
    }//GEN-LAST:event_EntrarActionPerformed

